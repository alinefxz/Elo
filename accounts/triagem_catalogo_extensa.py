"""Catálogo versionado da triagem extensa.

Cada código é estável e corresponde ao documento de especificação enviado para
o projeto. As regras ficam junto das alternativas para serem auditáveis e para
que o motor não dependa do texto mostrado na tela.
"""

REGRA_VERSION = "HEMOMINAS_2026_08"

TEMPORARIA = "INAPTIDAO_TEMPORARIA"
DEFINITIVA = "INAPTIDAO_DEFINITIVA"
AVALIACAO = "AVALIACAO_PRESENCIAL"
DOCUMENTACAO = "DOCUMENTACAO_ESPECIAL"


def opcao(codigo, rotulo):
    """Cria uma alternativa com código próprio para persistência."""

    return {"codigo": codigo, "rotulo": rotulo}


def regra(resultado, mensagem, prazo=None, exige_relatorio=False):
    """Cria uma regra declarativa consumida pelo motor da triagem."""

    return {
        "resultado": resultado,
        "mensagem": mensagem,
        "prazo": prazo,
        "exige_relatorio": exige_relatorio,
    }


def pergunta(
    id_pergunta,
    titulo,
    texto,
    explicacao,
    opcoes,
    *,
    multipla=False,
    permite_data=False,
    exige_data_para=(),
    mostrar_se=None,
    regras=None,
    fonte="Manual Elo; ref. [1]",
):
    """Padroniza todos os campos esperados pelas demais camadas."""

    return {
        "id": id_pergunta,
        "titulo": titulo,
        "texto": texto,
        "explicacao": explicacao,
        "tipo": "escolha",
        "opcoes": [opcao(*item) for item in opcoes],
        "multipla": multipla,
        "permite_data": permite_data,
        "exige_data_para": list(exige_data_para),
        "mostrar_se": mostrar_se,
        "abrir_extensa": {},
        "regras": regras or {},
        "fonte": fonte,
        "regra_version": REGRA_VERSION,
    }


def pergunta_tabela(
    id_pergunta,
    titulo,
    texto,
    explicacao,
    itens,
    *,
    permite_data=True,
    fonte="Manual Elo; ref. [1]",
):
    """Monta perguntas longas em que várias condições podem ser marcadas."""

    opcoes = []
    regras = {}
    exige_data = []

    for codigo, rotulo, resultado, mensagem, prazo in itens:
        opcoes.append((codigo, rotulo))
        if resultado:
            regras[codigo] = regra(resultado, mensagem, prazo)
        if prazo:
            exige_data.append(codigo)

    return pergunta(
        id_pergunta,
        titulo,
        texto,
        explicacao,
        opcoes,
        multipla=True,
        permite_data=permite_data,
        exige_data_para=exige_data,
        regras=regras,
        fonte=fonte,
    )


